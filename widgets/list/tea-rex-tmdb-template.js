/// sort_by 为空或残留的 default 哨兵都不发给 TMDB，交回接口自己的顺序；
/// 声明里的 release_date.* 是中性取值，按最终端点换成 TMDB 的日期字段。
function applySortBy(params, type) {
  if (!params.sort_by || params.sort_by === "default") {
    delete params.sort_by;
    return;
  }
  const dateField = type === "movie" ? "primary_release_date" : "first_air_date";
  if (params.sort_by === "release_date.desc") {
    params.sort_by = `${dateField}.desc`;
  } else if (params.sort_by === "release_date.asc") {
    params.sort_by = `${dateField}.asc`;
  }
}


function isKnownRegion(region) {
  return [
    "chinese", "western", "british", "taiwan", "hong_kong",
    "japanese", "korean", "thai",
  ].indexOf(region) >= 0;
}

function regionForLanguage(language) {
  var normalized = String(language || "").replace(/_/g, "-").toLowerCase();
  if (normalized === "yue" || normalized.indexOf("yue-") === 0) {
    return "hong_kong";
  }
  if (normalized.indexOf("zh-") === 0 || normalized === "zh") {
    if (
      normalized.indexOf("-hk") >= 0
      || normalized.indexOf("-mo") >= 0
      || normalized.indexOf("hant-hk") >= 0
    ) {
      return "hong_kong";
    }
    if (normalized.indexOf("-tw") >= 0 || normalized.indexOf("hant") >= 0) {
      return "taiwan";
    }
    return "chinese";
  }
  if (normalized === "ja" || normalized.indexOf("ja-") === 0) {
    return "japanese";
  }
  if (normalized === "ko" || normalized.indexOf("ko-") === 0) {
    return "korean";
  }
  if (normalized === "th" || normalized.indexOf("th-") === 0) {
    return "thai";
  }
  if (normalized === "en-gb") {
    return "british";
  }
  return "western";
}

function resolveRegion(params) {
  var selected = params && params.region;
  if (selected && selected !== "auto" && isKnownRegion(selected)) {
    return selected;
  }
  return regionForLanguage(params && params.language);
}

function compactDate(date) {
  return date.getUTCFullYear().toString()
    + (date.getUTCMonth() + 1).toString().padStart(2, "0")
    + date.getUTCDate().toString().padStart(2, "0");
}

function recentDateKeys(firstDate) {
  var keys = [];
  if (isRecentDateKey(firstDate)) {
    keys.push(firstDate);
  }
  for (var offset = 0; offset < 7; offset += 1) {
    var target = new Date();
    target.setUTCHours(0, 0, 0, 0);
    target.setUTCDate(target.getUTCDate() - offset);
    var key = compactDate(target);
    if (keys.indexOf(key) < 0) {
      keys.push(key);
    }
  }
  return keys;
}

function isRecentDateKey(value) {
  if (typeof value !== "string" || !/^\d{8}$/.test(value)) {
    return false;
  }
  var year = Number(value.slice(0, 4));
  var month = Number(value.slice(4, 6));
  var day = Number(value.slice(6, 8));
  var parsed = new Date(Date.UTC(year, month - 1, day));
  if (
    parsed.getUTCFullYear() !== year
    || parsed.getUTCMonth() !== month - 1
    || parsed.getUTCDate() !== day
  ) {
    return false;
  }
  var today = new Date();
  today.setUTCHours(0, 0, 0, 0);
  var ageInDays = Math.floor((today.getTime() - parsed.getTime()) / 86400000);
  return ageInDays >= 0 && ageInDays < 7;
}


/// 只保留带 TMDB id 的电影，返回与 fetchData 相同的条目形状。
/// 兼容扁平条目与 { douban_info, tmdb_info } 两种导出结构。
function formatDoubanMovies(payload) {
  if (!Array.isArray(payload)) {
    return [];
  }
  var result = [];
  var seen = {};
  for (var index = 0; index < payload.length; index += 1) {
    var media = payload[index];
    if (!media || !media.tmdb_info || !media.tmdb_info.id) {
      continue;
    }
    var douban = media.douban_info || media;
    var tmdbInfo = media.tmdb_info;
    var mediaType = tmdbInfo.mediaType || (douban.is_tv ? "tv" : "movie");
    if (mediaType !== "movie") {
      continue;
    }
    var key = String(tmdbInfo.id);
    if (seen[key]) {
      continue;
    }
    seen[key] = true;
    var genres = Array.isArray(douban.genres) && douban.genres.length > 0
      ? douban.genres.join(", ")
      : (tmdbInfo.genreTitle || "");
    result.push({
      id: tmdbInfo.id,
      type: "tmdb",
      title: douban.title || tmdbInfo.title || "",
      description: tmdbInfo.description || douban.summary || "",
      releaseDate: tmdbInfo.releaseDate || douban.release_date || "",
      backdropPath: tmdbInfo.backdropPath || "",
      // 豆瓣 poster_url 是豆瓣站内相对路径，不能当 TMDB 图片路径用。
      posterPath: tmdbInfo.posterPath || "",
      rating: tmdbInfo.rating || douban.rating || 0,
      mediaType: "movie",
      genreTitle: genres,
    });
  }
  return result;
}

